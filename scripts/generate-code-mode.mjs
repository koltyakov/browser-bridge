// @ts-check
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';
import { createMethodInputs, schemaSignature, validateMcpMetadata } from './generate-catalog.mjs';
import { generateGzip } from './generated-gzip.mjs';

/** @typedef {import('./generate-catalog.mjs').MethodInput} MethodInput */
/** @typedef {{[key: string]: Tree | string}} Tree */

/** Render the same method tree as types and executable closures.
 * @param {Tree} tree
 * @param {boolean} runtime
 * @returns {string}
 */
function renderTree(tree, runtime) {
  const fields = Object.entries(tree).map(([key, child]) => {
    if (typeof child !== 'string')
      return `${runtime ? '' : 'readonly '}${JSON.stringify(key)}: ${renderTree(child, runtime)}`;
    return runtime
      ? `${JSON.stringify(key)}: bind(${JSON.stringify(child)})`
      : `readonly ${JSON.stringify(key)}: BrowserMethodCall<${JSON.stringify(child)}, Result>`;
  });
  return runtime ? `Object.freeze({${fields.join(',\n')}})` : `{${fields.join(';\n')}}`;
}

/** Pure generation from the same selected schemas used by RPC discovery.
 * @param {Record<string, MethodInput>} inputs
 * @param {import('../protocol/mcp-metadata.js').McpMetadata} metadata
 * @returns {{typescript: string, declarations: string}}
 */
export function createCodeModeSources(inputs, metadata) {
  const tool = metadata.allTools.find((entry) => entry.name === 'browser_call');
  assert(tool?.inputSchema.properties, 'Code Mode needs canonical browser_call metadata');
  const routing = Object.fromEntries(
    Object.entries(tool.inputSchema.properties).filter(
      ([key]) => !['method', 'params'].includes(key)
    )
  );
  const methods = Object.keys(inputs).sort();
  /** @type {Tree} */
  const tree = {};
  for (const method of methods) {
    let branch = tree;
    const segments = method.split('.');
    for (const segment of segments.slice(0, -1)) {
      assert(/^[a-z][a-z0-9_]*$/.test(segment), `Invalid Code Mode segment: ${segment}`);
      const child = branch[segment] ?? (branch[segment] = {});
      assert(typeof child !== 'string', `Code Mode method/namespace collision: ${method}`);
      branch = child;
    }
    const leaf = segments.at(-1);
    assert(
      leaf && /^[a-z][a-z0-9_]*$/.test(leaf) && !branch[leaf],
      `Invalid Code Mode method: ${method}`
    );
    branch[leaf] = method;
  }
  const header = '// Generated by scripts/generate-code-mode.mjs. DO NOT EDIT.\n';
  const types = `
/** Selected canonical RPC inputs. Nested website-authored data remains untrusted. */
export interface BrowserMethodParams {
${methods.map((method) => `${JSON.stringify(method)}: ${Object.keys(inputs[method].inputSchema.properties).length ? schemaSignature(inputs[method].inputSchema) : 'Record<string, never>'};`).join('\n')}
}
export type BrowserMethod = keyof BrowserMethodParams;
/** Defaults are routing conveniences, not security boundaries or grants. */
export type BrowserRouting = ${schemaSignature({ type: 'object', properties: routing, additionalProperties: false })};
export type BrowserCallOptions = BrowserRouting & { signal?: AbortSignal };
export type BrowserCallArguments = {
  [Method in BrowserMethod]: BrowserRouting & { method: Method; params: BrowserMethodParams[Method] }
}[BrowserMethod];
/** Supply the host's existing browser_call. Preserve its result and error contract. */
export type BrowserCall<Result> = (args: BrowserCallArguments, options?: { signal?: AbortSignal }) => Promise<Result>;
export type BrowserMethodCall<Method extends BrowserMethod, Result> =
  {} extends BrowserMethodParams[Method]
    ? (params?: BrowserMethodParams[Method], options?: BrowserCallOptions) => Promise<Result>
    : (params: BrowserMethodParams[Method], options?: BrowserCallOptions) => Promise<Result>;
export type BrowserBridge<Result> = ${renderTree(tree, false)};
`;
  const signature =
    'export function createBrowserBridge<Result>(call: BrowserCall<Result>, defaults: BrowserRouting = {}): BrowserBridge<Result>';
  const implementation = `
/** No transport, retries, page evaluation, or implicit browser actions.
 * Every invocation goes through the supplied host tool and its Go runtime. */
${signature} {
  if (typeof call !== 'function') throw new TypeError('Supply the host browser_call callback');
  const keys = new Set<string>(${JSON.stringify(Object.keys(routing))});
  function routingOptions(value: BrowserRouting, allowSignal = false): BrowserRouting {
    const result: Record<string, unknown> = {};
    for (const key of Object.keys(value)) {
      if (allowSignal && key === 'signal') continue;
      if (!keys.has(key)) throw new TypeError('Unknown browser_call option: ' + key);
      const entry = value[key as keyof BrowserRouting];
      if (entry !== undefined) result[key] = entry;
    }
    return result;
  }
  // Routing values are primitive. Snapshot defaults so callers cannot silently
  // redirect already-created bindings by mutating the defaults object.
  const base = routingOptions(defaults);
  async function invoke<Method extends BrowserMethod>(
    method: Method,
    params: BrowserMethodParams[Method] | undefined,
    options: BrowserCallOptions = {},
  ): Promise<Result> {
    options.signal?.throwIfAborted();
    const args = { ...base, ...routingOptions(options, true), method, params: params ?? {} };
    // The generated leaf correlates method and params. The host and Go still
    // validate every call; TypeScript is not an authorization mechanism.
    return call(args as BrowserCallArguments, options.signal ? { signal: options.signal } : undefined);
  }
  function bind<Method extends BrowserMethod>(method: Method): BrowserMethodCall<Method, Result> {
    return ((params?: BrowserMethodParams[Method], options?: BrowserCallOptions) =>
      invoke(method, params, options)) as BrowserMethodCall<Method, Result>;
  }
  return ${renderTree(tree, true)};
}
`;
  return {
    typescript: header + types + implementation,
    declarations:
      header +
      types +
      '\n/** Bind the host browser_call without opening a connection or replaying calls. */\n' +
      signature
        .replace('export function', 'export declare function')
        .replace('defaults: BrowserRouting = {}', 'defaults?: BrowserRouting') +
      ';\n',
  };
}

/** Generate standalone source, ESM and declarations for embedding in the Go CLI.
 * @param {boolean} check
 * @param {string} [root]
 * @returns {Promise<void>}
 */
export async function generateCodeMode(
  check,
  root = fileURLToPath(new URL('../', import.meta.url))
) {
  const metadata = /** @type {unknown} */ (
    JSON.parse(await fs.readFile(path.join(root, 'protocol/mcp-tools.json'), 'utf8'))
  );
  validateMcpMetadata(metadata);
  const wire = /** @type {{$defs: Record<string, unknown>}} */ (
    JSON.parse(await fs.readFile(path.join(root, 'protocol/generated/bridge.schema.json'), 'utf8'))
  );
  const sources = createCodeModeSources(createMethodInputs(wire.$defs), metadata);
  const javascript = await transform(sources.typescript, {
    loader: 'ts',
    format: 'esm',
    target: 'es2020',
  });
  for (const [extension, content] of Object.entries({
    ts: sources.typescript,
    mjs: '// Generated from browser-bridge.ts. DO NOT EDIT.\n' + javascript.code,
    'd.mts': sources.declarations,
  })) {
    const filename = path.join(
      root,
      'internal/bridge/generated/code-mode',
      `browser-bridge.${extension}`
    );
    if (check) {
      assert.equal(
        await fs.readFile(filename, 'utf8').catch(() => ''),
        content,
        'Generated Code Mode adapter is stale. Run make generate-protocol.'
      );
    } else {
      await fs.mkdir(path.dirname(filename), { recursive: true });
      await fs.writeFile(filename, content);
    }
    await generateGzip(`${filename}.gz`, Buffer.from(content), check);
  }
}
