// @ts-check
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const local = 'github.com/koltyakov/browser-bridge/internal/readability';

/** Remove only the encoding-aware reader entry point. The pinned checksum makes
 * these exact boundaries part of the reviewed transformation, not a Go parser.
 * @param {string} source
 * @returns {string}
 */
export function documentOnlyParser(source) {
  const start = source.indexOf('// Parse parses a reader');
  const end = source.indexOf('// ParseDocument parses');
  assert(start > 0 && end > start, 'Upstream reader API boundaries changed');
  const reader = source.slice(start, end);
  assert(reader.includes('func (ps *Parser) Parse(input io.Reader,'));
  assert(reader.includes('dom.Parse(input)'));
  return (source.slice(0, start) + source.slice(end)).replace('\n\t"io"', '');
}

/** Reproduce the audited document-only subset from checksum-pinned modules.
 * Module downloads are verified by Go against go.sum. Ordinary builds use only
 * the checked-in output and never run this script or fetch source.
 * @param {boolean} check
 * @param {string} [directory]
 * @returns {Promise<void>}
 */
export async function vendorReadability(check, directory = root) {
  const manifest = /** @type {Record<string, Record<string, string>>} */ (
    JSON.parse(await fs.readFile(new URL('./readability-sources.json', import.meta.url), 'utf8'))
  );
  for (const [module, files] of Object.entries(manifest)) {
    const result = /** @type {{Dir: string, Error?: string}} */ (
      JSON.parse(
        execFileSync('go', ['mod', 'download', '-json', module], { cwd: root, encoding: 'utf8' })
      )
    );
    assert(result.Dir && !result.Error, `Cannot load pinned module ${module}`);
    const isDOM = module.startsWith('github.com/go-shiori/dom@');
    for (const [name, hash] of Object.entries(files)) {
      let content = await fs.readFile(path.join(result.Dir, name), 'utf8');
      assert.equal(
        createHash('sha256').update(content).digest('hex'),
        hash,
        `Unreviewed source: ${module}/${name}`
      );
      if (name === 'parser-parse.go') content = documentOnlyParser(content);
      if (name.endsWith('.go')) {
        content = content
          .replaceAll(
            'codeberg.org/readeck/go-readability/v2/internal/re2go',
            `${local}/internal/re2go`
          )
          .replaceAll('codeberg.org/readeck/go-readability/v2/render', `${local}/render`)
          .replaceAll('github.com/go-shiori/dom', `${local}/internal/dom`);
        content = `// Code generated by scripts/vendor-readability.mjs from ${module}/${name}. DO NOT EDIT.\n\n${content}`;
        content = execFileSync('gofmt', [], { input: content, encoding: 'utf8' });
      }
      const output = path.join(
        directory,
        'internal/readability',
        isDOM ? 'internal/dom' : '',
        name
      );
      if (check) {
        assert.equal(
          await fs.readFile(output, 'utf8').catch(() => ''),
          content,
          `Audited Readability subset is stale: ${output}`
        );
      } else {
        await fs.mkdir(path.dirname(output), { recursive: true });
        await fs.writeFile(output, content);
      }
    }
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await vendorReadability(process.argv.includes('--check'));
}
